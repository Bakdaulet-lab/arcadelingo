/// Календарный день в хранилище: `ГГГГ-ММ-ДД` и обратно.
///
/// Формат хранения, а не отладочный вывод. `StreakDay.toString()` сегодня
/// выглядит так же, но он для человека в сообщении упавшего теста — завязать
/// на него формат документа значит однажды сломать чужие данные, поправив
/// строку в тесте.
///
/// Отдельным файлом, а не приватным помощником журнала: формат дня — это
/// свойство хранилища, а не одной таблицы, и место для него должно быть
/// очевидным раньше, чем появится третий желающий.
///
/// Кодек серии (`streak_codec.dart`) на него **не переведён**, хотя формат
/// там тот же. Причина не в лени: он различает «строка не похожа на дату» и
/// «дата не существует» разными сообщениями `Failure` — это разные улики, и
/// тест «несуществующая дата, а не смещение на март» написан именно про
/// вторую. [decodeDay] обе сваливает в null. Переводить его значило бы ради
/// четырёх строк ухудшить диагностику в чужом, уже принятом коде.
///
/// Разбор строгий и свой, не `DateTime.parse`: у дня нет зоны и нет времени
/// (`domain/streak/streak.dart`), а `parse` принял бы и момент со смещением,
/// молча превратив его в день. Ведущие нули обязательны — на них держится
/// свойство, ради которого формат и выбран: лексикографический порядок строк
/// совпадает с календарным, и отрезок дней в SQL выбирается обычным
/// `BETWEEN`, без единой функции работы с датами.
library;

import 'package:arcadelingo/domain/streak/streak.dart';

/// Ровно дата и ничего кроме: ни времени, ни зоны, ни лишних цифр.
final RegExp _dayFormat = RegExp(r'^(\d{4})-(\d{2})-(\d{2})$');

/// Длина записи дня. Ею же ограничена колонка журнала.
const int dayTextLength = 10;

/// День → строка хранилища.
String encodeDay(StreakDay day) =>
    '${day.year.toString().padLeft(4, '0')}-'
    '${day.month.toString().padLeft(2, '0')}-'
    '${day.day.toString().padLeft(2, '0')}';

/// Строка хранилища → день, или null, если строка не день.
///
/// Возвращает null, а не бросает: разбирать битое хранилище — работа
/// вызывающего кодека, и `ArgumentError` из `StreakDay` сторожит инвариант,
/// а не читает документ. Несуществующая дата (`2026-02-31`) — тоже null.
StreakDay? decodeDay(String text) {
  final match = _dayFormat.firstMatch(text);
  if (match == null) return null;
  return StreakDay.tryCreate(
    int.parse(match.group(1)!),
    int.parse(match.group(2)!),
    int.parse(match.group(3)!),
  );
}
