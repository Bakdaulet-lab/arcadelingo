/// История в SQLite через Drift: пока одна таблица ответов, схема v1.
///
/// Имя базы — `HistoryDatabase`, а не `AnswerDatabase`: рядом с ответами
/// на Этапе 3.2 ложится журнал событий, и база перестаёт быть про один
/// вид записей. **Имя файла на устройстве при этом не меняется**
/// (`wordarcade_answers`) — переименование осиротило бы уже записанное.
///
/// Почему БД, а не третий JSON-документ в prefs. Журнал растёт без потолка —
/// 15 ответов в день это ~5 500 строк в год, — и документ пришлось бы
/// целиком перечитывать и переписывать на каждый ответ. Плюс схема будет
/// меняться: Фаза 3 добавит события открытия и отвала, SM-2 — свои поля.
/// Ровно эти два свойства и отличают журнал от карточек, которые в БД **не**
/// переезжают (`docs/dev/context.md`).
///
/// ## Ограничение по SQL
///
/// Тесты, CI и телефон едут на **трёх разных сборках sqlite**: на Windows
/// `winsqlite3.dll` из системы, на CI — системная `libsqlite3.so.0`, на
/// устройстве — своя из `sqlite3_flutter_libs`. Версии расходятся (3.45 и
/// 3.51 на момент этапа), поэтому SQL здесь держится в объёме, одинаковом
/// для обеих: без `RETURNING`, без `STRICT`-таблиц. Запрос, который зелен
/// локально и падает на телефоне, — худший из возможных.
///
/// ## Почему момент лежит целым числом
///
/// `DateTimeColumn` у Drift по умолчанию хранит секунды с эпохи, и доли
/// секунды теряются. Переигровка (`domain/log/replay.dart`) сравнивает `due`
/// карточек буквально, и потерянные микросекунды сделали бы её ложно-красной.
/// Поэтому момент — микросекунды UTC целым числом: без потерь, без зоны и без
/// зависимости от того, как очередная версия Drift решит хранить даты.
///
/// День при этом лежит отдельной текстовой колонкой, а не считается из
/// момента: из UTC локальный день не восстановим (`AnswerRecord.localDay`).
/// Формат `ГГГГ-ММ-ДД` с ведущими нулями выбран не для красоты — при нём
/// лексикографическое сравнение строк совпадает с календарным, и отрезок дней
/// выбирается обычным `BETWEEN` без единой функции работы с датами.
library;

import 'package:arcadelingo/domain/srs/review_grade.dart';
import 'package:drift/drift.dart';

part 'history_database.g.dart';

/// Ответы: append-only, строки не меняются и не удаляются.
@TableIndex(name: 'answers_word', columns: {#wordId})
@TableIndex(name: 'answers_day', columns: {#localDay})
class Answers extends Table {
  /// Суррогатный ключ. Он же — вторичный порядок при равных моментах: два
  /// ответа в одну микросекунду невозможны на живых часах, но возможны на
  /// подставленных, и порядок переигровки не должен от этого зависеть.
  IntColumn get id => integer().autoIncrement()();

  /// Слово из сида. Само слово не хранится: оно живёт в ассете и меняется
  /// вместе с ним, а копия в журнале через год начала бы врать.
  TextColumn get wordId => text()();

  /// Момент ответа: микросекунды с эпохи, UTC.
  IntColumn get atUtcMicros => integer()();

  /// Локальный календарный день игравшего, `ГГГГ-ММ-ДД`.
  TextColumn get localDay => text().withLength(min: 10, max: 10)();

  /// Оценка для планировщика — именем значения перечисления.
  ///
  /// Сохранена, а не пересчитывается при чтении: переигровка обязана
  /// прогонять те оценки, которые действительно применялись, а `gradeOutcome`
  /// со временем может измениться. Переименование значения `ReviewGrade` —
  /// миграция данных, а не рефакторинг.
  TextColumn get grade => textEnum<ReviewGrade>()();

  /// Сырой факт от игры, как в `ReviewOutcome`.
  BoolColumn get correct => boolean()();
  IntColumn get responseMicros => integer()();
  IntColumn get limitMicros => integer()();
  IntColumn get hintsUsed => integer()();

  /// Идентификатор из реестра `lib/app/games.dart`.
  TextColumn get gameId => text()();

  /// Партия, внутри которой случился ответ.
  TextColumn get sessionId => text()();
}

@DriftDatabase(tables: [Answers])
class HistoryDatabase extends _$HistoryDatabase {
  HistoryDatabase(super.e);

  /// Версия схемы. Растёт вместе с изменениями таблицы; переход пишется
  /// явной миграцией — той же дисциплиной, что `version` в документах prefs.
  @override
  int get schemaVersion => 1;
}
