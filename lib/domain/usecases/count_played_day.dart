/// Засчитать сегодняшний день в серию.
///
/// Второй usecase фазы и замена наблюдателю. До Фазы 3 серию двигал
/// `StreakObserver` — по первому ответу дня; это было единственным доступным
/// сигналом, потому что о конце партии хост не знал. Правило Фазы 3 другое:
/// день засчитывает **законченная партия**, а не первый ответ, и выход на
/// восьмом слове днём не считается.
///
/// Отсюда и форма: это не наблюдатель, а действие, которое хост совершает,
/// когда партия кончилась. Чем именно она кончилась — итогами, потерянными
/// жизнями или тем, что повторять было нечего, — здесь не спрашивают
/// (`advanceStreak`, шапка правила).
///
/// Заведён отдельно от [StartSession] по той же причине, что и он сам: чтобы
/// «партия кончилась — серия продлилась» проверялось чистым тестом на
/// in-memory порту, без дерева виджетов.
library;

import 'dart:async';

import '../core/result.dart';
import '../ports/streak_store.dart';
import '../streak/streak.dart';

class CountPlayedDay {
  CountPlayedDay({
    required StreakStore streaks,
    required DateTime Function() now,
  }) : _streaks = streaks,
       _now = now;

  final StreakStore _streaks;
  final DateTime Function() _now;

  /// Состояние серии после сегодняшнего дня, или [Err], если документ не
  /// читается.
  ///
  /// Читает хранилище каждый раз, а не держит состояние в поле: между двумя
  /// партиями приложение могло уйти в фон и вернуться, а документ — быть
  /// сброшенным с экрана ошибки. Чтение из prefs синхронно и стоит дёшево.
  ///
  /// Если день уже засчитан, [advanceStreak] вернёт то же состояние, и
  /// записи не будет вовсе: серия меняется раз в день, а не раз в партию.
  Result<StreakState> call() {
    final StreakState before;
    switch (_streaks.load()) {
      case Ok(:final value):
        before = value;
      case Err(:final failure):
        return Err(failure);
    }
    final after = advanceStreak(before, StreakDay.of(_now()));
    // Сравнение по значению: `advanceStreak` вправе вернуть новый объект с
    // теми же полями, а писать в хранилище, когда писать нечего, значит
    // трогать документ на каждой второй партии за день.
    if (after != before) {
      // `unawaited`, как и везде: обработчик конца партии синхронен, ждать
      // запись некому. Потеря строки в полёте при убийстве приложения даёт
      // «серия не продлилась сегодня», и это чинится следующей партией.
      unawaited(_streaks.save(after));
    }
    return Ok(after);
  }
}
