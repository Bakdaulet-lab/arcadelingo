/// Переигровка журнала: состояние карточек, выведенное из истории ответов.
///
/// Это главный проверяемый результат Этапа 2.3, и проверяет он сразу две
/// вещи. Первая — журнал полон: ни один `report()` не потерян, иначе карта
/// не сойдётся. Вторая — журнал согласован с расписанием: те же оценки в том
/// же порядке дают то же расписание, то есть в журнале лежит именно то, на
/// чём стоит планировщик, а не похожие данные.
///
/// Тот же код с `sm2.schedule` вместо [schedule] станет инструментом оценки
/// SM-2 — прогнать накопленную историю через нового планировщика и посмотреть,
/// где он расходится с прожитым. Данные к этому копятся с этого этапа, а
/// раньше их не было вовсе.
///
/// Чистая функция: ни часов, ни хранилища. Время каждого шага приходит из
/// самой записи.
library;

import '../srs/leitner.dart';
import 'answer_record.dart';

/// Карта карточек, восстановленная из [log] с чистого состояния.
///
/// Повторяет ровно то, что делает `LeitnerReviewSession.report()`: новое
/// слово получает карточку первой коробки со сроком «сейчас», дальше
/// [schedule] от момента ответа. Дублирования правила здесь нет — правило
/// одно и живёт в `schedule`; здесь только его применение по порядку.
///
/// [log] обязан идти в хронологическом порядке: Лейтнер не коммутативен,
/// `again` после `easy` и `easy` после `again` дают разные коробки. Порядок
/// — забота источника ([AnswerLog.all] обещает его явно).
///
/// **Точность `due` держится ровно настолько, насколько совпадают часы.**
/// Сессия берёт `now()` для расписания, наблюдатель — для события, и это два
/// разных вызова. Под подставленными часами тестов они дают один и тот же
/// момент, и карта сходится буквально. На живых часах между ними проходят
/// микросекунды, и `due` разойдётся на столько же; коробка при этом та же
/// самая всегда — она от момента не зависит. Разбор — `docs/dev/context.md`.
///
/// История до появления журнала неизвестна, и восстановить её неоткуда:
/// переигровка верна для состояния, начатого с пустого журнала.
Map<String, LeitnerCard> replayCards(Iterable<AnswerRecord> log) {
  final cards = <String, LeitnerCard>{};
  for (final record in log) {
    // Слово, встреченное впервые, приходит из первой коробки со сроком
    // «сейчас» — ровно так его заводит сессия в момент первого ответа.
    final before =
        cards[record.wordId] ??
        LeitnerCard(box: LeitnerCard.minBox, due: record.at);
    cards[record.wordId] = schedule(before, record.grade, now: record.at);
  }
  return cards;
}
