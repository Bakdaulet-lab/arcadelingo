/// Наблюдатель, который пишет ответ в журнал.
///
/// Второй потребитель шва из `observed_session.dart` после [StreakObserver] и
/// повод, ради которого шов заводился: журнал понадобился через этап после
/// серии, и сессию для него менять не пришлось.
library;

import 'dart:async';

import '../ports/answer_log.dart';
import '../session/observed_session.dart';
import 'answer_record.dart';

class LoggingObserver implements ReviewObserver {
  LoggingObserver({required AnswerLog log}) : _log = log;

  final AnswerLog _log;

  /// Пишет строку и не ждёт записи.
  ///
  /// `unawaited` — по той же причине, что и у карточек с серией: `onAnswer`
  /// синхронен, ждать некому. Цена честная и здесь она ниже, чем везде:
  /// при убийстве приложения теряется строка в полёте, то есть последний
  /// ответ не попадёт в историю. Карточка при этом сохранится своим путём,
  /// и переигровка на такой истории разойдётся с состоянием на один ответ —
  /// это известный предел журнала, а не поломка.
  ///
  /// Отказ записи партию не отменяет — но и не замалчивается. `catch` здесь
  /// нет: упавший `append` становится необработанной асинхронной ошибкой,
  /// то есть красным тестом у нас и строкой в логе у пользователя, пока
  /// игра продолжается. Глушить его `catchError`'ом значило бы прятать баг
  /// записи навсегда, а журнал, который молча ничего не пишет, хуже
  /// отсутствующего.
  @override
  void onAnswer(ReviewEvent event) {
    // Заглушка красного коммита: пустое тело, а не бросок. Наблюдатель уже
    // подключён в StartSession, и бросок отсюда уронил бы все существующие
    // тесты партии — красным стало бы не то, что проверяется.
  }
}
