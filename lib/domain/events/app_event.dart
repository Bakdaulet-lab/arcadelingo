/// События приложения: чем именно человек занят, когда не отвечает на слова.
///
/// `ROADMAP.md` требует аналитику с первого дня Фазы 3 — «без неё нечего
/// тюнить». Тюнить в этой фазе собираются ритуал и напоминание, а вопросы к
/// ним ровно четыре: открыл ли приложение, начал ли партию, дошёл ли до конца,
/// бросил ли на середине. Больше в первой версии нет ничего, и это не
/// экономия: событие, которое некому прочитать, отличается от отсутствующего
/// только строчкой в таблице.
///
/// **Стороннего SDK здесь нет и в этой фазе не будет.** Вопросы сейчас задаёт
/// автор про себя и про бету из нескольких человек — на них полностью
/// отвечает локальная таблица, и она не тянет за собой ни политику
/// приватности, ни сетевые разрешения, ни возрастной рейтинг. Firebase и
/// прочее — триггер Фазы 5, там же, где бета на живых людях.
///
/// Соседство с журналом ответов не случайно: у них одна природа —
/// append-only история, — один файл и одна миграция. Разница в том, что
/// ответ порождает игра, а событие порождает **хост**: ни одно из
/// перечисленных ниже событий игра не знает и знать не должна.
library;

import '../streak/streak.dart';

/// Что случилось. Значения — ключи в хранилище: переименование расходится с
/// уже записанной историей, как и `gameId` в реестре игр.
enum AppEventKind {
  /// Приложение открыли и показали домашний экран.
  appOpen,

  /// Партия началась: сессия собрана и игра запущена.
  roundStart,

  /// Партия дошла до экрана конца — итогов или «жизни кончились».
  roundOver,

  /// Из партии вышли, не доиграв.
  roundAbandon,

  /// Напоминание поставлено в расписание.
  reminderScheduled,

  /// Приложение открыли тапом по напоминанию.
  reminderOpened,
}

/// Одно событие приложения.
class AppEvent {
  const AppEvent({
    required this.kind,
    required this.at,
    required this.localDay,
    this.sessionId,
  });

  /// Событие в момент [at]; день берётся из живого момента, пока при нём ещё
  /// есть зона хоста.
  factory AppEvent.at(AppEventKind kind, DateTime at, {String? sessionId}) =>
      AppEvent(
        kind: kind,
        at: at,
        localDay: StreakDay.of(at),
        sessionId: sessionId,
      );

  final AppEventKind kind;

  /// Момент. Прочитанный из хранилища — всегда в UTC, как и у ответа.
  final DateTime at;

  /// Локальный календарный день — хранится, а не считается из [at]: из UTC он
  /// не восстановим (`domain/log/answer_record.dart`).
  final StreakDay localDay;

  /// Партия, к которой относится событие; null у тех, что к партии отношения
  /// не имеют (открытие приложения, напоминание).
  ///
  /// По нему события сходятся с ответами: `AnswerRecord.sessionId` — то же
  /// самое значение, и «начал, но не доиграл» видно без единого нового поля.
  final String? sessionId;

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is AppEvent &&
          kind == other.kind &&
          at == other.at &&
          localDay == other.localDay &&
          sessionId == other.sessionId;

  @override
  int get hashCode => Object.hash(kind, at, localDay, sessionId);

  @override
  String toString() =>
      'AppEvent(${kind.name}, at: $at, day: $localDay, session: $sessionId)';
}
