/// Порт хранилища карточек: то, что доменному слою нужно от `data/`.
///
/// До Фазы 2 хост звал `LeitnerPrefsStore` напрямую, и это работало, пока
/// звал его один экран. С появлением usecase'а зависимость развернулась:
/// `StartSession` живёт в `domain/` и о `data/` знать не может (пункт 1
/// «Архитектурного закона»), поэтому хранилище приходит сюда интерфейсом,
/// а реализацию подключает композиционный корень.
///
/// [load] синхронный намеренно. На этом стоит «сессия создаётся по тапу»:
/// тап «Играть» → чтение → сессия, без единого `await` между ними, и тест
/// «очередь строится на момент тапа» держится именно на этом. Асинхронное
/// чтение здесь переписало бы весь этот путь ради нуля пользы — разбор в
/// `docs/dev/context.md`, решение Фазы 2 про Drift.
library;

import '../core/result.dart';
import '../srs/leitner.dart';

/// Состояние повторения: карточки по id слова.
abstract class CardStore {
  /// Сохранённое состояние. Пусто — первый запуск, не ошибка. Битый
  /// документ — [Err]; реализация при этом ничего не сбрасывает сама.
  Result<Map<String, LeitnerCard>> load();

  /// Записывает [cards] как полное состояние: документ заменяется, не
  /// сливается. Возвращает ответ платформы.
  Future<bool> save(Map<String, LeitnerCard> cards);

  /// Удаляет документ: следующий [load] — первый запуск. Зовётся только по
  /// нажатию человека, автосброса в коде нет.
  Future<bool> reset();
}
