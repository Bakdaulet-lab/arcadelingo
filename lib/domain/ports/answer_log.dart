/// Порт журнала ответов: то, что доменному слою нужно от хранилища истории.
///
/// Третий порт после [CardStore] и [StreakStore], и первый, за которым стоит
/// не документ, а таблица. Домен об этом не знает и знать не должен: здесь
/// только интерфейс, реализацию (`lib/data/log/`) подключает композиционный
/// корень.
///
/// Все методы асинхронны, и это не противоречит решению «`load()` карточек
/// синхронный». Карточки читаются в момент тапа «Играть», и от них зависит,
/// какая партия начнётся; журнал не читают во время партии вообще — пишут
/// вслед за ответом и читают на экране прогресса. Разбор — `context.md`,
/// решение Фазы 2 про Drift.
///
/// Ошибки здесь не заворачиваются в [Result], в отличие от обоих документов
/// прогресса. Причина в природе данных: битый JSON в prefs — правдоподобный
/// случай, документ лежит открытым текстом и переживает обновления приложения;
/// битая строка в собственной БД — либо баг записи, либо повреждённый файл, и
/// молчаливого продолжения ни то, ни другое не заслуживает. Журнал к тому же
/// не на пути игры: его отказ не должен уметь отменить партию.
library;

import '../log/answer_record.dart';
import '../streak/streak.dart';

/// История ответов: пишется всегда, читается редко, не изменяется никогда.
abstract class AnswerLog {
  /// Дописывает одну строку. Уже записанные не трогает.
  Future<void> append(AnswerRecord record);

  /// Весь журнал в хронологическом порядке — то, из чего переигровка
  /// (`domain/log/replay.dart`) восстанавливает состояние карточек.
  ///
  /// Читает всё целиком намеренно: переигровке нужна вся история, выборка
  /// сделала бы её ответ неправдой. При 15 ответах в день это ~5 500 строк в
  /// год; когда счёт пойдёт на сотни тысяч, переигровка станет фоновой
  /// операцией — но не раньше, и не гаданием сегодня.
  Future<List<AnswerRecord>> all();

  /// Ответы по одному слову, в хронологическом порядке.
  ///
  /// Первый потребитель — оценка SM-2: промахивается ли интервал видно по
  /// истории одного слова, а не по средним.
  Future<List<AnswerRecord>> forWord(String wordId);

  /// Сводка по дням из отрезка [from]..[to], включая обе границы.
  ///
  /// Дни без ответов в результат не попадают: их отсутствие — тоже ответ, и
  /// достраивать пустые дни обязан тот, кто рисует график, а не хранилище.
  Future<List<DayTally>> perDay({
    required StreakDay from,
    required StreakDay to,
  });
}

/// Журнал, который ничего не пишет и ничего не помнит.
///
/// Умолчание для всех, кому журнал не нужен: тестов, которые о нём не знают,
/// и любого хоста, который его не подключил. Не «заглушка на время
/// разработки», а нулевой объект — приложение с ним работает полностью, просто
/// без истории.
class NoopAnswerLog implements AnswerLog {
  const NoopAnswerLog();

  @override
  Future<void> append(AnswerRecord record) async {}

  @override
  Future<List<AnswerRecord>> all() async => const [];

  @override
  Future<List<AnswerRecord>> forWord(String wordId) async => const [];

  @override
  Future<List<DayTally>> perDay({
    required StreakDay from,
    required StreakDay to,
  }) async => const [];
}
