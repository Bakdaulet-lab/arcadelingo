/// Порт звука: игра говорит, что случилось, а не чем это озвучить.
///
/// Ровно как [Reminders] и [AnswerLog]: имя события, а не имя файла. Игра
/// не знает ни про `assets/sound/`, ни про пакет воспроизведения — иначе
/// `lib/features/` знал бы про `lib/data/`, а это пункт 4 «Архитектурного
/// закона».
///
/// Метод синхронный и без `Future`. Причина та же, что у `onCardsChanged`:
/// звук зовут из обработчика жеста, в кадре касания, и ждать там нечего —
/// проигрывание либо началось, либо нет, и на игру это не влияет никак.
/// Отказ звука партию не отменяет и в [Result] не заворачивается.
library;

import '../settings/app_settings.dart';

/// Что случилось. Не «какой файл», а «какое событие»: подмена файла — дело
/// адаптера, и порт про неё не знает.
enum GameSound {
  /// Верный рез.
  slice,

  /// Верный рез на горячей серии — тот же свист с тоном поверх.
  sliceHot,

  /// Промах или таймаут.
  miss,
}

abstract class Sounds {
  /// Сыграть [sound]. Не ждёт и не докладывает: см. шапку файла.
  void play(GameSound sound);
}

/// Нулевой объект: приложение с ним работает полностью, просто молча.
///
/// Он же — умолчание везде, где звук не нужен: тест, которому звук
/// безразличен, о звуке не узнаёт. И он же — то, что хост подставляет
/// вместо адаптера, когда [AppSettings.soundOn] выключен: гасить звук
/// подменой порта честнее, чем стражем внутри адаптера, потому что тогда
/// «выключено» значит «никто не зовёт», а не «зовут и молчат».
class NoopSounds implements Sounds {
  const NoopSounds();

  @override
  void play(GameSound sound) {}
}
