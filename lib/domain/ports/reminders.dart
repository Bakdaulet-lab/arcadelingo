/// Порт напоминаний: то, что доменному слою нужно от платформы.
///
/// Локальное уведомление в выбранный человеком момент — это платформенные
/// API, и внутри Flutter их нет. Плагин живёт в `lib/data/`, а здесь —
/// интерфейс из двух методов, ради которого домен остаётся без единого
/// стороннего пакета (пункт 1 «Архитектурного закона»).
///
/// Момент приходит обычным [DateTime] в местной зоне. Превращать его в то,
/// что понимает платформа, — работа адаптера: это он знает про зоны и про
/// то, что расписание у него неточное.
library;

abstract class Reminders {
  /// Ставит **единственное** напоминание, заменяя прежнее.
  ///
  /// Единственное намеренно: напоминание перепланируется после каждой партии
  /// и на каждом открытии приложения, и очередь из накопленных уведомлений
  /// быстро разошлась бы с тем, что человек видит на экране.
  Future<void> schedule({
    required DateTime at,
    required String title,
    required String body,
  });

  /// Снимает всё запланированное. Зовётся при выключении напоминаний.
  Future<void> cancelAll();
}

/// Напоминания, которых нет.
///
/// Умолчание для тестов и для хоста, который плагин не подключил.
/// Приложение с ним работает полностью, просто молча.
class NoopReminders implements Reminders {
  const NoopReminders();

  @override
  Future<void> schedule({
    required DateTime at,
    required String title,
    required String body,
  }) async {}

  @override
  Future<void> cancelAll() async {}
}
