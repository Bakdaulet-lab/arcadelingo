/// Решения джуса ниндзя-слэша: что чувствует рука, насколько сдвинут экран,
/// был ли рез сделан в последний момент.
///
/// **Это копия `falling_words_juice.dart`, а не общий код.** Правило 5
/// «Архитектурного закона»: игры — острова, и импорт соседа роняет
/// `arch_check.sh`. Цена названа вслух — числа продублированы в двух файлах
/// и разъедутся, если править их порознь; выгода в том, что падающие слова
/// можно менять, не сверяясь с ниндзя. Список скопированного целиком лежит
/// в плане Фазы 4 и в `/new-game`: это **кандидаты в общее**, которые
/// выделит третья игра, а не свалка.
///
/// Файл намеренно без Flutter — даже без `dart:ui`. Причина та же, что у
/// оригинала: [isNearMiss] нужен `NinjaRun`, а тот держится без Flutter,
/// потому что страж «ровно один `report()` на слово» обязан проверяться без
/// дерева виджетов. Один `Color`, приехавший сюда за компанию, утащил бы
/// Flutter и туда.
///
/// Числа — `SPEC.md`, раздел «Ниндзя-слэш» → «Джус». Здесь они названы, а не
/// объяснены.
library;

import 'dart:math';

/// Что чувствует рука. Три значения, различимые на ощупь: больше рука не
/// различает, меньше — не хватает, чтобы отделить потерю жизни от успеха.
enum Haptic { light, medium, heavy }

/// С какой серии верный рез отдаётся средним откликом вместо лёгкого.
const int comboHapticFrom = 5;

/// Порог «в последний момент»: 17/20, то есть последние 15% полёта.
///
/// Дробью, а не `0.85`: сравнение идёт по целым микросекундам, и на самой
/// границе результат не должен зависеть от того, как машина округлила
/// литерал.
const int nearMissNumerator = 17;

/// Знаменатель порога — см. [nearMissNumerator].
const int nearMissDenominator = 20;

/// Награда за рез в последний момент — полуторная. Тоже дробью и тоже
/// целочисленно: `(очки * 3) ~/ 2`.
const int nearMissBonusNumerator = 3;

/// Знаменатель награды — см. [nearMissBonusNumerator].
const int nearMissBonusDenominator = 2;

/// Сколько трясёт после промаха. Короче подсветки (800 мс) намеренно:
/// оставшееся время пара «слово → перевод» стоит неподвижно.
const Duration shakeTime = Duration(milliseconds: 300);

/// Первый пик тряски в логических пикселях.
const double shakeAmplitude = 8;

/// Полных колебаний за [shakeTime].
const int shakeOscillations = 3;

/// Что отдать руке по итогу реза.
///
/// [combo] — серия **после** ответа, то есть ноль при промахе: именно её
/// виджет читает с `NinjaRun` в момент вызова, и просить его вычитать
/// единицу значило бы завести вторую формулу серии.
Haptic hapticFor({
  required bool correct,
  required int combo,
  required bool nearMiss,
}) {
  if (!correct) return Haptic.heavy;
  if (nearMiss || combo >= comboHapticFrom) return Haptic.medium;
  return Haptic.light;
}

/// Сделан ли рез в последние 15% отпущенного времени.
///
/// Про верность реза функция не знает и знать не должна: бонус только
/// верному — правило начисления, и живёт оно в `NinjaRun`.
bool isNearMiss({required Duration responseTime, required Duration timeLimit}) {
  if (timeLimit <= Duration.zero) return false;
  // Умножением, а не делением: доля 0.85 в double на самой границе окна
  // округляется в разные стороны на разных платформах, а порядок величин
  // здесь такой, что произведение целых не переполнится и близко.
  return responseTime.inMicroseconds * nearMissDenominator >=
      timeLimit.inMicroseconds * nearMissNumerator;
}

/// Смещение в долях [shakeAmplitude]; [t] — доля прожитого времени тряски.
///
/// Значения вне 0…1 зажимаются: часы тряски идут от чужого контроллера, и
/// округление на его конце не должно выбрасывать экран за амплитуду.
double shakeIntensity(double t) {
  final progress = t.clamp(0.0, 1.0);
  // Косинус, а не синус: первый экстремум обязан прийтись на нулевой кадр.
  // С синусом экран сначала стоял бы ровно и разгонялся к пику — это
  // читается как «поехало», а не как «ударило».
  return (1 - progress) * cos(2 * pi * shakeOscillations * progress);
}
